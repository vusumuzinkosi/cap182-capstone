"""Export summaries of the feature effect for the fitted SS2 models.

The logistic regression coefficient has directionality: positive coefficients lead to
higher and negative coefficients lead to lower fitted log-odds of subscriptions,
given the other coded predictors. XGBoost feature importance is the normalized
classifier importance which is neither directional nor causal.
"""
from __future__ import annotations

import os

import joblib
import pandas as pd

from common import MODELS_DIR, RESULTS_DIR


def _readable(name: str) -> str:
    return name.replace("num__", "").replace("cat__", "")


def _markdown_table(frame: pd.DataFrame, value_col: str) -> list[str]:
    lines = ["| Rank | Feature | Value |", "|---:|---|---:|"]
    for rank, (_, row) in enumerate(frame.iterrows(), 1):
        lines.append(f"| {rank} | `{_readable(row['feature'])}` | {row[value_col]:.4f} |")
    return lines


def main() -> int:
    model1 = joblib.load(os.path.join(MODELS_DIR, "model1_logreg.joblib"))
    model2 = joblib.load(os.path.join(MODELS_DIR, "model2_xgboost.joblib"))

    names1 = model1.named_steps["preprocess"].get_feature_names_out()
    names2 = model2.named_steps["preprocess"].get_feature_names_out()
    if list(names1) != list(names2):
        raise RuntimeError("Model feature orders differ; explanation is unsafe.")

    effects = pd.DataFrame({
        "feature": names1,
        "logreg_coefficient": model1.named_steps["clf"].coef_[0],
        "xgboost_importance": model2.named_steps["clf"].feature_importances_,
    })
    effects.to_csv(os.path.join(RESULTS_DIR, "feature_effects.csv"), index=False)

    positive = effects.nlargest(10, "logreg_coefficient")
    negative = effects.nsmallest(10, "logreg_coefficient")
    xgb = effects.nlargest(10, "xgboost_importance")

    md = [
        "# Feature-effect summary (generated by explain_models.py)", "",
        "These rankings describe fitted associations, not causal effects. Logistic",
        "coefficients are directional; XGBoost importance is non-directional.", "",
        "## Logistic Regression - strongest positive coefficients", "",
        *_markdown_table(positive, "logreg_coefficient"), "",
        "## Logistic Regression - strongest negative coefficients", "",
        *_markdown_table(negative, "logreg_coefficient"), "",
        "## XGBoost - highest feature importances", "",
        *_markdown_table(xgb, "xgboost_importance"), "",
    ]
    with open(os.path.join(RESULTS_DIR, "feature_effects.md"), "w", encoding="utf-8") as stream:
        stream.write("\n".join(md))

    print("Wrote feature_effects.csv and feature_effects.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
