"""
compare_models.py -- direct comparison between Model 1 and Model 2 (CAP182 SS2).

It reads the predictions saved by both models and generates the following:
  - Metrics table combining results (experimental-results/comparison_summary.md & .csv)
  - McNemar’s test for predictions made by the models (is there a significant difference between their errors?)
  - Overlaid ROC and PR curves (experimental-results/roc_pr_comparison.png)

This script should be run after both training scripts.
Run: python scripts/compare_models.py
Map: Comparison.MD
"""
from __future__ import annotations
import os, json
import numpy as np
import pandas as pd

# Keep Matplotlib's font/config cache inside the project so headless runs do not
# depend on a writable user home directory.
_MPL_CACHE = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "experimental-results", ".matplotlib-cache",
)
os.makedirs(_MPL_CACHE, exist_ok=True)
os.environ.setdefault("MPLCONFIGDIR", _MPL_CACHE)

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.stats import binomtest, chi2
from sklearn.metrics import roc_curve, precision_recall_curve, auc, average_precision_score

from common import RESULTS_DIR


def _load(model_no: int):
    preds = pd.read_csv(os.path.join(RESULTS_DIR, f"model{model_no}_predictions.csv"))
    with open(os.path.join(RESULTS_DIR, f"model{model_no}_metrics.json")) as f:
        metrics = json.load(f)
    return preds, metrics


def mcnemar(y_true, pred1, pred2) -> dict:
    correct1 = (pred1 == y_true)
    correct2 = (pred2 == y_true)
    b = int(np.sum(correct1 & ~correct2))   # M1 right, M2 wrong
    c = int(np.sum(~correct1 & correct2))   # M1 wrong, M2 right
    n = b + c
    if n == 0:
        return {"b": b, "c": c, "statistic": 0.0, "p_value": 1.0}
    stat = (abs(b - c) - 1) ** 2 / n         # chi-square, continuity-corrected
    p_chi = float(chi2.sf(stat, df=1))
    p_exact = float(binomtest(min(b, c), n, 0.5).pvalue)
    return {"b": b, "c": c, "statistic": float(stat),
            "p_value_chi2": p_chi, "p_value_exact": p_exact}


def main() -> int:
    p1, m1 = _load(1)
    p2, m2 = _load(2)
    y = p1["y_true"].values

    # combined metrics table 
    rows = ["accuracy", "balanced_accuracy", "precision", "recall",
            "specificity", "f1", "roc_auc", "pr_auc"]
    table = pd.DataFrame({
        m1["model"]: [m1[k] for k in rows],
        m2["model"]: [m2[k] for k in rows],
    }, index=rows)
    table["difference (M2 - M1)"] = table[m2["model"]] - table[m1["model"]]
    table.to_csv(os.path.join(RESULTS_DIR, "comparison_summary.csv"))

    # McNemar
    mc = mcnemar(y, p1["y_pred"].values, p2["y_pred"].values)

    # Markdown summary
    md = ["# Model Comparison Summary (generated by compare_models.py)", "",
          "## Metrics (held-out test set)", "",
          "| Metric | " + m1["model"] + " | " + m2["model"] + " | M2 - M1 |",
          "|---|---|---|---|"]
    for k in rows:
        md.append(f"| {k} | {m1[k]:.4f} | {m2[k]:.4f} | {m2[k]-m1[k]:+.4f} |")
    md += ["", "## McNemar's test (paired predictions)", "",
           f"- Discordant pairs: b (M1 right / M2 wrong) = {mc['b']}, "
           f"c (M1 wrong / M2 right) = {mc['c']}",
           f"- chi-square (cc) = {mc['statistic']:.3f}, p = {mc.get('p_value_chi2', 1):.4g}",
           f"- exact binomial p = {mc.get('p_value_exact', 1):.4g}",
           "",
           "A small p-value indicates the two models make significantly "
           "different errors; the sign of c - b shows which model is right more "
           "often on the disagreements.", ""]
    with open(os.path.join(RESULTS_DIR, "comparison_summary.md"), "w") as f:
        f.write("\n".join(md))

    # ROC + PR plots
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))
    for preds, meta, colour in [(p1, m1, "#1f77b4"), (p2, m2, "#d62728")]:
        fpr, tpr, _ = roc_curve(preds["y_true"], preds["y_proba"])
        ax1.plot(fpr, tpr, color=colour, label=f"{meta['model']} (AUC={auc(fpr,tpr):.3f})")
        prec, rec, _ = precision_recall_curve(preds["y_true"], preds["y_proba"])
        ap = average_precision_score(preds["y_true"], preds["y_proba"])
        ax2.plot(rec, prec, color=colour, label=f"{meta['model']} (AP={ap:.3f})")
    ax1.plot([0, 1], [0, 1], "k--", alpha=0.4)
    ax1.set_xlabel("False positive rate"); ax1.set_ylabel("True positive rate")
    ax1.set_title("ROC curve"); ax1.legend(loc="lower right")
    base = float(np.mean(y))
    ax2.axhline(base, ls="--", color="grey", alpha=0.6, label=f"No-skill ({base:.3f})")
    ax2.set_xlabel("Recall"); ax2.set_ylabel("Precision")
    ax2.set_title("Precision-Recall curve"); ax2.legend(loc="upper right")
    fig.tight_layout()
    fig.savefig(os.path.join(RESULTS_DIR, "roc_pr_comparison.png"), dpi=130)

    print("\n=== Comparison ===")
    print(table.round(4).to_string())
    print("\nMcNemar:", mc)
    print("\nWrote comparison_summary.md, comparison_summary.csv, roc_pr_comparison.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
